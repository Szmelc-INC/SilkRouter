package shell

import (
	"fmt"
	"strings"
	"text/template"
)

// InitOptions shape the init script.
type InitOptions struct {
	Bin        string   // absolute path of the binary (falls back to $PATH)
	Names      []string // wrapper function names: px, s-proxy, silkrouter
	Hooks      bool     // preexec / precmd command logging
	P10K       string   // left | right | none: add the segment to powerlevel10k
	PromptAuto bool     // plain prompts: prefix while the proxy is on
	Version    string
}

// Init renders the init script for sh (zsh, bash or fish).
func Init(sh string, o InitOptions) (string, error) {
	if len(o.Names) == 0 {
		o.Names = []string{"px", "s-proxy", "silkrouter"}
	}
	if o.P10K == "" {
		o.P10K = "none"
	}
	var src string
	switch sh {
	case "zsh":
		src = zshInit
	case "bash":
		src = bashInit
	case "fish":
		src = fishInit
	default:
		return "", fmt.Errorf("unsupported shell %q (want %s)", sh, strings.Join(Shells, ", "))
	}
	t, err := template.New(sh).Funcs(template.FuncMap{"sq": QuoteSh, "fq": QuoteFish}).Parse(src)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	if err := t.Execute(&b, o); err != nil {
		return "", err
	}
	return b.String(), nil
}

const zshInit = `# SilkRouter shell integration for zsh (silkrouter {{.Version}}).
# Generated by 'silkrouter shell-init zsh'; load it from ~/.zshrc with
#   eval "$(silkrouter shell-init zsh)"     (or: silkrouter shell install)
# It defines the wrapper functions that make 'px on' / 'px off' / 'px rotate'
# change this shell's environment, logs every command typed while a proxy
# is on, and shows a prompt segment (powerlevel10k: 'silkrouter').

typeset -g SILKROUTER_BIN=${SILKROUTER_BIN:-{{sq .Bin}}}
[[ -x $SILKROUTER_BIN ]] || SILKROUTER_BIN=silkrouter

__silkrouter_wrap() {
  case "$1" in
    on|off|rotate)
      local __silkrouter_out
      __silkrouter_out="$(SILKROUTER_SHELL_FN=1 command "$SILKROUTER_BIN" "$1" --emit zsh "${@:2}")" || return $?
      eval "$__silkrouter_out"
      ;;
    *)
      command "$SILKROUTER_BIN" "$@"
      ;;
  esac
}
{{range .Names}}function {{.}}() { __silkrouter_wrap "$@" }
{{end}}
{{- if .Hooks}}
# ---- command log (preexec / precmd) ----
zmodload zsh/datetime 2>/dev/null
autoload -Uz add-zsh-hook
__silkrouter_preexec() {
  [[ -n $SILKROUTER_ACTIVE && $SILKROUTER_LOG == 1 ]] || return 0
  typeset -g __silkrouter_cmd=$1 __silkrouter_t0=$EPOCHREALTIME
}
__silkrouter_precmd() {
  local __ec=$?
  if [[ -n $__silkrouter_cmd && -n $SILKROUTER_ACTIVE ]]; then
    local __t0=${${__silkrouter_t0/./}[1,13]} __t1=${${EPOCHREALTIME/./}[1,13]}
    command "$SILKROUTER_BIN" -q __shell-log --proxy "$SILKROUTER_PROXY" --session "$SILKROUTER_SESSION" \
      --start "$__t0" --end "$__t1" --exit "$__ec" --cwd "$PWD" --tty "$TTY" -- "$__silkrouter_cmd" \
      >/dev/null 2>&1 &!
  fi
  unset __silkrouter_cmd
  return $__ec
}
add-zsh-hook preexec __silkrouter_preexec
# First in precmd_functions, so $? is still the command's exit status.
precmd_functions=(__silkrouter_precmd ${precmd_functions:#__silkrouter_precmd})
{{- end}}

# ---- prompt ----
# powerlevel10k segment: add 'silkrouter' to POWERLEVEL9K_LEFT_PROMPT_ELEMENTS
# (or RIGHT); colors: POWERLEVEL9K_SILKROUTER_FOREGROUND / _BACKGROUND.
prompt_silkrouter() {
  [[ -n $SILKROUTER_ACTIVE ]] || return
  p10k segment -f "${SILKROUTER_COLOR:-208}" -i "${SILKROUTER_ICON}" -t "${SILKROUTER_PROMPT_TEXT//\%/%%}"
}
instant_prompt_silkrouter() { prompt_silkrouter }
{{- if ne .P10K "none"}}
__silkrouter_p10k_setup() {
  precmd_functions=(${precmd_functions:#__silkrouter_p10k_setup})
  (( ${+functions[p10k]} )) || return 0
  (( ${POWERLEVEL9K_LEFT_PROMPT_ELEMENTS[(Ie)silkrouter]} || ${POWERLEVEL9K_RIGHT_PROMPT_ELEMENTS[(Ie)silkrouter]} )) && return 0
  {{- if eq .P10K "right"}}
  typeset -ga POWERLEVEL9K_RIGHT_PROMPT_ELEMENTS=(silkrouter $POWERLEVEL9K_RIGHT_PROMPT_ELEMENTS)
  {{- else}}
  local -i __i=${POWERLEVEL9K_LEFT_PROMPT_ELEMENTS[(I)vcs]}
  (( __i )) || __i=$(( ${POWERLEVEL9K_LEFT_PROMPT_ELEMENTS[(I)dir]} + 1 ))
  (( __i > 1 )) || __i=$(( ${#POWERLEVEL9K_LEFT_PROMPT_ELEMENTS} + 1 ))
  typeset -ga POWERLEVEL9K_LEFT_PROMPT_ELEMENTS=("${(@)POWERLEVEL9K_LEFT_PROMPT_ELEMENTS[1,__i-1]}" silkrouter "${(@)POWERLEVEL9K_LEFT_PROMPT_ELEMENTS[__i,-1]}")
  {{- end}}
  p10k reload 2>/dev/null
}
precmd_functions+=(__silkrouter_p10k_setup)
{{- end}}
{{- if .PromptAuto}}
# Plain zsh prompts (no powerlevel10k): prefix PROMPT while the proxy is on.
__silkrouter_prompt() {
  (( ${+functions[p10k]} )) && return 0
  [[ -n $__silkrouter_seg ]] && PROMPT=${PROMPT#"$__silkrouter_seg"}
  if [[ -n $SILKROUTER_ACTIVE ]]; then
    typeset -g __silkrouter_seg="%F{${SILKROUTER_COLOR:-208}}${SILKROUTER_PROMPT//\%/%%}%f "
    PROMPT="$__silkrouter_seg$PROMPT"
  else
    typeset -g __silkrouter_seg=""
  fi
}
precmd_functions+=(__silkrouter_prompt)
{{- end}}
`

const bashInit = `# SilkRouter shell integration for bash (silkrouter {{.Version}}).
# Generated by 'silkrouter shell-init bash'; load it from ~/.bashrc with
#   eval "$(silkrouter shell-init bash)"    (or: silkrouter shell install bash)

SILKROUTER_BIN=${SILKROUTER_BIN:-{{sq .Bin}}}
[ -x "$SILKROUTER_BIN" ] || SILKROUTER_BIN=silkrouter

__silkrouter_wrap() {
  case "$1" in
    on|off|rotate)
      local __silkrouter_out
      __silkrouter_out="$(SILKROUTER_SHELL_FN=1 command "$SILKROUTER_BIN" "$1" --emit bash "${@:2}")" || return $?
      eval "$__silkrouter_out"
      ;;
    *)
      command "$SILKROUTER_BIN" "$@"
      ;;
  esac
}
{{range .Names}}{{.}}() { __silkrouter_wrap "$@"; }
{{end}}
__silkrouter_ms() { local t=${EPOCHREALTIME/[.,]/}; [ -n "$t" ] && echo $(( t / 1000 )) || date +%s000; }
{{- if .Hooks}}
# ---- command log ----
__silkrouter_preexec() {
  [ -n "$COMP_LINE" ] && return
  [ -n "$__silkrouter_armed" ] || return
  [ -n "$SILKROUTER_ACTIVE" ] && [ "$SILKROUTER_LOG" = 1 ] || return
  __silkrouter_armed=
  __silkrouter_cmd=$(HISTTIMEFORMAT= builtin history 1 | sed 's/^ *[0-9]* *//')
  __silkrouter_t0=$(__silkrouter_ms)
}
__silkrouter_precmd() {
  local __ec=$?
  if [ -n "$__silkrouter_cmd" ] && [ -n "$SILKROUTER_ACTIVE" ]; then
    (command "$SILKROUTER_BIN" -q __shell-log --proxy "$SILKROUTER_PROXY" --session "$SILKROUTER_SESSION" \
      --start "$__silkrouter_t0" --end "$(__silkrouter_ms)" --exit "$__ec" --cwd "$PWD" --tty "$(tty 2>/dev/null)" \
      -- "$__silkrouter_cmd" >/dev/null 2>&1 &)
  fi
  __silkrouter_cmd=
  return $__ec
}
# Armed by the last PROMPT_COMMAND entry, so only the next typed command
# (not the prompt's own commands) reaches the DEBUG trap.
__silkrouter_arm() { __silkrouter_armed=1; }
if declare -F __bp_preexec_invoke_exec >/dev/null 2>&1; then
  # bash-preexec is loaded: use its hook arrays.
  preexec_functions+=(__silkrouter_preexec_bp)
  __silkrouter_preexec_bp() { __silkrouter_armed=1; __silkrouter_preexec; }
  precmd_functions=(__silkrouter_precmd "${precmd_functions[@]}")
elif [ -z "$(trap -p DEBUG)" ]; then
  trap '__silkrouter_preexec' DEBUG
  PROMPT_COMMAND="__silkrouter_precmd${PROMPT_COMMAND:+; $PROMPT_COMMAND}"
fi
{{- end}}
{{- if .PromptAuto}}
# ---- prompt: prefix PS1 while the proxy is on ----
__silkrouter_ps1() {
  local ec=$?
  [ -n "$__silkrouter_seg" ] && PS1=${PS1#"$__silkrouter_seg"}
  if [ -n "$SILKROUTER_ACTIVE" ]; then
    local c=${SILKROUTER_COLOR:-208}
    case $c in *[!0-9]*) c=208 ;; esac
    __silkrouter_seg="\[\e[38;5;${c}m\]${SILKROUTER_PROMPT}\[\e[0m\] "
    PS1="$__silkrouter_seg$PS1"
  else
    __silkrouter_seg=
  fi
  return $ec
}
PROMPT_COMMAND="${PROMPT_COMMAND:+$PROMPT_COMMAND; }__silkrouter_ps1"
{{- end}}
{{- if .Hooks}}
case "$PROMPT_COMMAND" in *__silkrouter_precmd*) PROMPT_COMMAND="$PROMPT_COMMAND; __silkrouter_arm" ;; esac
{{- end}}
`

const fishInit = `# SilkRouter shell integration for fish (silkrouter {{.Version}}).
# Generated by 'silkrouter shell-init fish'; load it from config.fish with
#   silkrouter shell-init fish | source      (or: silkrouter shell install fish)

set -q SILKROUTER_BIN; or set -g SILKROUTER_BIN {{fq .Bin}}
test -x "$SILKROUTER_BIN"; or set -g SILKROUTER_BIN silkrouter

function __silkrouter_wrap
    switch "$argv[1]"
        case on off rotate
            set -l out (env SILKROUTER_SHELL_FN=1 $SILKROUTER_BIN $argv[1] --emit fish $argv[2..-1]); or return $status
            printf '%s\n' $out | source
        case '*'
            command $SILKROUTER_BIN $argv
    end
end
{{range .Names}}function {{.}} --wraps silkrouter
    __silkrouter_wrap $argv
end
{{end}}
{{- if .Hooks}}
function __silkrouter_preexec --on-event fish_preexec
    set -q SILKROUTER_ACTIVE; and test "$SILKROUTER_LOG" = 1; or return
    set -g __silkrouter_cmd $argv[1]
end
function __silkrouter_postexec --on-event fish_postexec
    set -l ec $status
    set -q __silkrouter_cmd; and set -q SILKROUTER_ACTIVE; or return
    command $SILKROUTER_BIN -q __shell-log --proxy "$SILKROUTER_PROXY" --session "$SILKROUTER_SESSION" \
        --duration "$CMD_DURATION" --exit $ec --cwd "$PWD" --tty (tty 2>/dev/null) -- "$__silkrouter_cmd" >/dev/null 2>&1 &
    disown 2>/dev/null
    set -e __silkrouter_cmd
end
{{- end}}
{{- if .PromptAuto}}
if functions -q fish_prompt; and not functions -q __silkrouter_orig_prompt
    functions -c fish_prompt __silkrouter_orig_prompt
    function fish_prompt
        if set -q SILKROUTER_ACTIVE
            set_color (string match -qr '^[0-9]+$' -- "$SILKROUTER_COLOR"; and echo yellow; or echo $SILKROUTER_COLOR)
            printf '%s ' "$SILKROUTER_PROMPT"
            set_color normal
        end
        __silkrouter_orig_prompt
    end
end
{{- end}}
`
