package cli

import (
	"bytes"
	"fmt"
	"io"
	"sort"
	"strings"
)

// dq double-quotes s for bash/fish case patterns.
func dq(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "$", `\$`, "`", "\\`")
	return `"` + r.Replace(s) + `"`
}

// offered returns the spellings a script offers for flags: -x and --long.
func offered(flags []*Flag) []string {
	var out []string
	for _, f := range flags {
		for _, n := range f.Short() {
			out = append(out, "-"+n)
		}
		for _, n := range f.Long() {
			out = append(out, "--"+n)
		}
	}
	return out
}

func (a *App) writeBash(w io.Writer, root *node) error {
	p := "_" + identRe.ReplaceAllString(a.Binary, "_")
	var b bytes.Buffer
	fmt.Fprintf(&b, "# bash completion for %s (%s).\n", a.Name, strings.Join(a.Names(), ", "))
	fmt.Fprintf(&b, "# Generated by `%s completion bash`; do not edit.\n", a.Binary)
	fmt.Fprintf(&b, "# Load it for the current shell:  source <(%s completion bash)\n\n", a.Binary)

	fmt.Fprintf(&b, "%s_dynamic() {\n  command \"$1\" __complete \"$2\" 2>/dev/null | cut -f1\n}\n\n", p)

	// Child path for (path, word) when word names a subcommand.
	fmt.Fprintf(&b, "%s_sub() {\n  case \"$1|$2\" in\n", p)
	root.walk(func(n *node) {
		for _, s := range n.subs {
			var pats []string
			for _, name := range s.names {
				pats = append(pats, dq(n.key()+"|"+name))
			}
			fmt.Fprintf(&b, "    %s) echo %s ;;\n", strings.Join(pats, "|"), dq(s.key()))
		}
	})
	b.WriteString("    *) return 1 ;;\n  esac\n}\n\n")

	// Flag names (no dashes) known at a path; value flags marked.
	fmt.Fprintf(&b, "%s_flag() {\n  # $1=path $2=name; prints \"value\" or \"bool\" for a known flag\n  case \"$1|$2\" in\n", p)
	root.walk(func(n *node) {
		var vals, bools []string
		for _, f := range n.flags {
			for _, name := range f.Names {
				pat := dq(n.key() + "|" + name)
				if f.TakesValue() {
					vals = append(vals, pat)
				} else {
					bools = append(bools, pat)
				}
			}
		}
		if len(vals) > 0 {
			fmt.Fprintf(&b, "    %s) echo value ;;\n", strings.Join(vals, "|"))
		}
		if len(bools) > 0 {
			fmt.Fprintf(&b, "    %s) echo bool ;;\n", strings.Join(bools, "|"))
		}
	})
	b.WriteString("    *) return 1 ;;\n  esac\n}\n\n")

	fmt.Fprintf(&b, `%[1]s_program() {
  # Complete the routed program (and its arguments) starting at word $1.
  if declare -F _command_offset >/dev/null 2>&1; then
    _command_offset "$1"
  elif (( COMP_CWORD == $1 )); then
    COMPREPLY=($(compgen -c -- "${COMP_WORDS[COMP_CWORD]}"))
  else
    compopt -o filenames 2>/dev/null
    COMPREPLY=($(compgen -f -- "${COMP_WORDS[COMP_CWORD]}"))
  fi
}

`, p)

	passThrough := map[string]bool{}
	root.walk(func(n *node) {
		if n.passThrough {
			passThrough[n.key()] = true
		}
	})
	var ptPats []string
	for k := range passThrough {
		ptPats = append(ptPats, dq(k))
	}
	sort.Strings(ptPats)
	fallback := a.Registry.Fallback

	fmt.Fprintf(&b, "%s() {\n", p)
	b.WriteString(`  local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]} prog=${COMP_WORDS[0]}
  if [[ $cur == "=" ]]; then
    cur=""
  elif [[ $prev == "=" ]]; then
    prev=${COMP_WORDS[COMP_CWORD-2]}
  fi
  COMPREPLY=()

  local path="" argc=0 skip=0 nomore=0 i w name next kind
  for ((i = 1; i < COMP_CWORD; i++)); do
    w=${COMP_WORDS[i]}
    if ((skip > 0)); then ((skip--)); continue; fi
    if ((!nomore)) && [[ $w == "--" ]]; then
`)
	if fallback != "" {
		fmt.Fprintf(&b, "      [[ -z $path ]] && path=%s\n", dq(fallback))
	}
	b.WriteString("      case $path in\n")
	if len(ptPats) > 0 {
		fmt.Fprintf(&b, "        %s) %s_program $((i + 1)); return ;;\n", strings.Join(ptPats, "|"), p)
	}
	b.WriteString(`      esac
      nomore=1; continue
    fi
    if ((!nomore)) && [[ $w == -?* ]]; then
      name=${w#-}; name=${name#-}; name=${name%%=*}
      if [[ -z $path ]]; then
        case ${w%%=*} in
`)
	for _, flagName := range a.legacyModeFlags() {
		m := a.Registry.LegacyModes[flagName]
		skip := 0
		if m.TakesValue {
			skip = 1
		}
		fmt.Fprintf(&b, "          %s) path=%s; [[ $w == *=* ]] || skip=%d; continue ;;\n", dq(flagName), dq(m.Command), skip)
	}
	b.WriteString("        esac\n")
	if fallback != "" {
		fmt.Fprintf(&b, "        %s_flag \"\" \"$name\" >/dev/null || path=%s\n", p, dq(fallback))
	}
	fmt.Fprintf(&b, `      fi
      kind=$(%[1]s_flag "$path" "$name")
      if [[ $kind == value && $w != *=* ]]; then
        [[ ${COMP_WORDS[i+1]} == "=" ]] && skip=2 || skip=1
      fi
      continue
    fi
    if ((!nomore)) && next=$(%[1]s_sub "$path" "$w"); then
      path=$next; argc=0; continue
    fi
`, p)
	if fallback != "" {
		fmt.Fprintf(&b, "    [[ -z $path ]] && path=%s\n", dq(fallback))
	}
	b.WriteString("    case $path in\n")
	if len(ptPats) > 0 {
		fmt.Fprintf(&b, "      %s) %s_program $i; return ;;\n", strings.Join(ptPats, "|"), p)
	}
	b.WriteString("    esac\n    ((argc++))\n  done\n\n")

	// Value of the previous flag.
	b.WriteString("  if [[ $prev == -?* ]] && ((!nomore)); then\n")
	b.WriteString("    name=${prev#-}; name=${name#-}; name=${name%%=*}\n")
	fmt.Fprintf(&b, "    if [[ $(%s_flag \"$path\" \"$name\") == value ]]; then\n      case \"$path|$name\" in\n", p)
	root.walk(func(n *node) {
		for _, f := range n.flags {
			if !f.TakesValue() || f.Complete.Kind == CompleteNone {
				continue
			}
			var pats []string
			for _, name := range f.Names {
				pats = append(pats, dq(n.key()+"|"+name))
			}
			fmt.Fprintf(&b, "        %s) %s ;;\n", strings.Join(pats, "|"), bashAction(f.Complete, p))
		}
	})
	b.WriteString("      esac\n      return\n    fi\n  fi\n\n")

	// Flags.
	b.WriteString("  if [[ $cur == -* ]] && ((!nomore)); then\n    case $path in\n")
	root.walk(func(n *node) {
		fmt.Fprintf(&b, "      %s) COMPREPLY=($(compgen -W %s -- \"$cur\")) ;;\n", dq(n.key()), zq(strings.Join(offered(n.flags), " ")))
	})
	b.WriteString("    esac\n    return\n  fi\n\n")

	// Positional arguments.
	b.WriteString("  case $path in\n")
	root.walk(func(n *node) {
		var act string
		switch {
		case len(n.subs) > 0:
			var words []string
			for _, s := range n.subs {
				words = append(words, s.names...)
			}
			act = fmt.Sprintf("COMPREPLY=($(compgen -W %s -- \"$cur\"))", zq(strings.Join(words, " ")))
		case n.args.Kind == CompleteCommand:
			act = `COMPREPLY=($(compgen -c -- "$cur"))`
		case n.args.Kind != CompleteNone:
			act = bashAction(n.args, p)
			if n.maxArgs == 1 {
				act = "((argc < 1)) && { " + act + "; }"
			}
		default:
			return
		}
		fmt.Fprintf(&b, "    %s) %s ;;\n", dq(n.key()), act)
	})
	b.WriteString("  esac\n}\n\n")

	fmt.Fprintf(&b, "complete -F %s %s\n", p, strings.Join(a.Names(), " "))
	_, err := w.Write(b.Bytes())
	return err
}

func bashAction(c Completion, p string) string {
	switch c.Kind {
	case CompleteFile:
		return `compopt -o filenames 2>/dev/null; COMPREPLY=($(compgen -f -- "$cur"))`
	case CompleteDir:
		return `compopt -o filenames 2>/dev/null; COMPREPLY=($(compgen -d -- "$cur"))`
	case CompleteChoices:
		return fmt.Sprintf(`COMPREPLY=($(compgen -W %s -- "$cur"))`, zq(strings.Join(c.Words, " ")))
	case CompleteDynamic:
		return fmt.Sprintf(`COMPREPLY=($(compgen -W "$(%s_dynamic "$prog" %s)" -- "$cur"))`, p, c.Topic)
	case CompleteCommand:
		return `COMPREPLY=($(compgen -c -- "$cur"))`
	}
	return ":"
}
