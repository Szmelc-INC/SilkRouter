package cli

import (
	"bytes"
	"fmt"
	"io"
	"strings"
)

// zq single-quotes s for zsh/bash.
func zq(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// zshDesc escapes text used inside an _arguments [description].
func zshDesc(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `[`, `\[`, `]`, `\]`, "\n", " ")
	return r.Replace(s)
}

// zshColon escapes colons (message / _describe value parts).
func zshColon(s string) string { return strings.ReplaceAll(s, ":", `\:`) }

func zshAction(c Completion, prefix string) string {
	switch c.Kind {
	case CompleteFile:
		return "_files"
	case CompleteDir:
		return "_files -/"
	case CompleteChoices:
		return "(" + strings.Join(c.Words, " ") + ")"
	case CompleteDynamic:
		return prefix + "_dynamic " + c.Topic
	}
	return " "
}

// zshFlagSpecs renders _arguments specs for flags.
func zshFlagSpecs(flags []*Flag, prefix string) []string {
	var out []string
	for _, f := range flags {
		var spell []string
		for _, n := range f.Short() {
			spell = append(spell, "-"+n)
		}
		for _, n := range f.Long() {
			if f.TakesValue() {
				spell = append(spell, "--"+n+"=")
			} else {
				spell = append(spell, "--"+n)
			}
		}
		desc := "[" + zshDesc(f.Usage) + "]"
		val := ""
		if f.TakesValue() {
			meta := f.Meta
			if meta == "" {
				meta = "value"
			}
			val = ":" + zshColon(meta) + ":" + zshAction(f.Complete, prefix)
		}
		if len(spell) == 1 {
			out = append(out, zq(spell[0]+desc+val))
			continue
		}
		var excl []string
		for _, s := range spell {
			excl = append(excl, strings.TrimSuffix(s, "="))
		}
		out = append(out, zq("("+strings.Join(excl, " ")+")")+"{"+strings.Join(spell, ",")+"}"+zq(desc+val))
	}
	return out
}

func (a *App) writeZsh(w io.Writer, root *node) error {
	p := "_" + identRe.ReplaceAllString(a.Binary, "_")
	var b bytes.Buffer
	names := strings.Join(a.Names(), " ")
	fmt.Fprintf(&b, "#compdef %s\n", names)
	fmt.Fprintf(&b, "# zsh completion for %s (%s).\n", a.Name, strings.Join(a.Names(), ", "))
	fmt.Fprintf(&b, "# Generated by `%s completion zsh`; do not edit.\n", a.Binary)
	b.WriteString("#\n# Install: put this file as _" + a.Binary + " in a directory on $fpath, or\n")
	fmt.Fprintf(&b, "# load it for the current shell:  source <(%s completion zsh)\n\n", a.Binary)

	// Dynamic values: `prog __complete TOPIC` prints "value<TAB>desc".
	fmt.Fprintf(&b, `%[1]s_dynamic() {
  local -a items
  local line
  for line in ${(f)"$(command ${%[1]s_prog:-%[2]s} __complete $1 2>/dev/null)"}; do
    items+=("${${line%%%%$'\t'*}//:/\\:}:${line#*$'\t'}")
  done
  _describe -t $1 $1 items
}

`, p, a.Binary)

	var err error
	root.walk(func(n *node) {
		if err == nil {
			err = zshNode(&b, n, p, a.Registry.Fallback)
		}
	})
	if err != nil {
		return err
	}

	fmt.Fprintf(&b, `%[1]s() {
  local %[1]s_prog=${words[1]}
  %[1]s__root "$@"
}

if [[ "${funcstack[1]}" == %[1]s ]]; then
  %[1]s "$@"
else
  compdef %[1]s %[2]s
fi
`, p, names)
	_, werr := w.Write(b.Bytes())
	return werr
}

func zshNode(b *bytes.Buffer, n *node, p, fallback string) error {
	fn := p + "__" + n.fn()
	specs := zshFlagSpecs(n.flags, p)

	if len(n.subs) > 0 {
		// Command list for this level.
		fmt.Fprintf(b, "%s_cmds() {\n  local -a commands\n  commands=(\n", fn)
		for _, s := range n.subs {
			for i, name := range s.names {
				desc := s.summary
				if i > 0 {
					desc = "alias for " + s.names[0] + ": " + s.summary
				}
				fmt.Fprintf(b, "    %s\n", zq(zshColon(name)+":"+desc))
			}
		}
		fmt.Fprintf(b, "  )\n  _describe -t commands command commands\n}\n\n")

		fmt.Fprintf(b, "%s() {\n", fn)
		b.WriteString("  local curcontext=\"$curcontext\" state state_descr line ret=1\n  typeset -A opt_args\n")
		b.WriteString("  _arguments -C -S \\\n")
		for _, s := range specs {
			fmt.Fprintf(b, "    %s \\\n", s)
		}
		fmt.Fprintf(b, "    '1: :%s_cmds' \\\n    '*:: :->sub' && ret=0\n", fn)
		b.WriteString("  case $state in\n    (sub)\n")
		fmt.Fprintf(b, "      curcontext=\"${curcontext%%:*:*}:%s-${words[1]}:\"\n", strings.TrimPrefix(p, "_"))
		b.WriteString("      case ${words[1]} in\n")
		for _, s := range n.subs {
			fmt.Fprintf(b, "        (%s) %s__%s && ret=0 ;;\n", strings.Join(s.names, "|"), p, s.fn())
		}
		if len(n.path) == 0 && fallback != "" {
			// Legacy px.sh style: the first word is a program to route.
			b.WriteString("        (*) _normal && ret=0 ;;\n")
		}
		b.WriteString("      esac\n      ;;\n  esac\n  return ret\n}\n\n")
		return nil
	}

	fmt.Fprintf(b, "%s() {\n", fn)
	opts := "-S"
	if n.passThrough {
		opts = "-S -A '-*'"
	}
	fmt.Fprintf(b, "  _arguments %s \\\n", opts)
	for _, s := range specs {
		fmt.Fprintf(b, "    %s \\\n", s)
	}
	pos := ""
	switch n.args.Kind {
	case CompleteCommand:
		pos = "'(-)1:command:_command_names -e' \\\n    '*::arguments:_normal'"
	case CompleteFile:
		pos = "'*:file:_files'"
	case CompleteDir:
		pos = "'*:directory:_files -/'"
	case CompleteChoices, CompleteDynamic:
		if n.maxArgs == 1 {
			pos = zq("1:value:" + zshAction(n.args, p))
		} else {
			pos = zq("*:value:" + zshAction(n.args, p))
		}
	}
	if pos == "" {
		// Drop the trailing continuation of the last spec.
		trimContinuation(b)
		b.WriteString("\n}\n\n")
		return nil
	}
	fmt.Fprintf(b, "    %s\n}\n\n", pos)
	return nil
}

// trimContinuation removes a trailing " \\\n" from b.
func trimContinuation(b *bytes.Buffer) {
	s := b.Bytes()
	if bytes.HasSuffix(s, []byte(" \\\n")) {
		b.Truncate(len(s) - 3)
	}
}
