package cli

import (
	"bytes"
	"fmt"
	"io"
	"strings"
)

// fq single-quotes s for fish.
func fq(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `'`, `\'`, "\n", " ")
	return "'" + r.Replace(s) + "'"
}

func (a *App) writeFish(w io.Writer, root *node) error {
	p := "__" + identRe.ReplaceAllString(a.Binary, "_")
	fallback := a.Registry.Fallback
	var b bytes.Buffer
	fmt.Fprintf(&b, "# fish completion for %s (%s).\n", a.Name, strings.Join(a.Names(), ", "))
	fmt.Fprintf(&b, "# Generated by `%s completion fish`; do not edit.\n", a.Binary)
	fmt.Fprintf(&b, "# Load it for the current shell:  %s completion fish | source\n\n", a.Binary)

	fmt.Fprintf(&b, "function %s_dynamic\n    set -l prog (commandline -opc)[1]\n    command $prog __complete $argv[1] 2>/dev/null\nend\n\n", p)

	// Subcommand table.
	fmt.Fprintf(&b, "function %s_sub --argument-names path word\n    switch \"$path|$word\"\n", p)
	root.walk(func(n *node) {
		for _, s := range n.subs {
			var pats []string
			for _, name := range s.names {
				pats = append(pats, fq(n.key()+"|"+name))
			}
			fmt.Fprintf(&b, "        case %s\n            echo %s\n", strings.Join(pats, " "), fq(s.key()))
		}
	})
	b.WriteString("    end\nend\n\n")

	// Flag table: prints "value" or "bool".
	fmt.Fprintf(&b, "function %s_flag --argument-names path name\n    switch \"$path|$name\"\n", p)
	root.walk(func(n *node) {
		var vals, bools []string
		for _, f := range n.flags {
			for _, name := range f.Names {
				pat := fq(n.key() + "|" + name)
				if f.TakesValue() {
					vals = append(vals, pat)
				} else {
					bools = append(bools, pat)
				}
			}
		}
		if len(vals) > 0 {
			fmt.Fprintf(&b, "        case %s\n            echo value\n", strings.Join(vals, " "))
		}
		if len(bools) > 0 {
			fmt.Fprintf(&b, "        case %s\n            echo bool\n", strings.Join(bools, " "))
		}
	})
	b.WriteString("        case '*'\n            return 1\n    end\nend\n\n")

	var pts []string
	root.walk(func(n *node) {
		if n.passThrough {
			pts = append(pts, fq(n.key()))
		}
	})

	// Path of the command line being completed. Once a pass-through
	// command's program has started it prints "<path>+" and stores the
	// program's token index in <p>_argi.
	fmt.Fprintf(&b, "function %s_path\n", p)
	b.WriteString(`    set -l tokens (commandline -opc)
    set -l path ''
    set -l skip 0
    set -l nomore 0
    set -l n (count $tokens)
    for i in (seq 2 $n)
        set -l w $tokens[$i]
        if test $skip -gt 0
            set skip (math $skip - 1)
            continue
        end
        if test $nomore -eq 0; and test "$w" = '--'
`)
	if fallback != "" {
		fmt.Fprintf(&b, "            test -z \"$path\"; and set path %s\n", fq(fallback))
	}
	if len(pts) > 0 {
		fmt.Fprintf(&b, "            if contains -- \"$path\" %s\n                set -g %s_argi (math $i + 1)\n                echo \"$path+\"\n                return\n            end\n", strings.Join(pts, " "), p)
	}
	b.WriteString(`            set nomore 1
            continue
        end
        if test $nomore -eq 0; and string match -qr -- '^-.' $w
            set -l name (string replace -r -- '^--?' '' $w | string replace -r -- '=.*$' '')
            if test -z "$path"
                switch (string replace -r -- '=.*$' '' $w)
`)
	for _, flagName := range a.legacyModeFlags() {
		m := a.Registry.LegacyModes[flagName]
		fmt.Fprintf(&b, "                    case %s\n                        set path %s\n", fq(flagName), fq(m.Command))
		if m.TakesValue {
			b.WriteString("                        string match -q -- '*=*' $w; or set skip 1\n")
		}
		b.WriteString("                        continue\n")
	}
	b.WriteString("                end\n")
	if fallback != "" {
		fmt.Fprintf(&b, "                %s_flag '' $name >/dev/null; or set path %s\n", p, fq(fallback))
	}
	fmt.Fprintf(&b, `            end
            set -l kind (%[1]s_flag "$path" $name)
            if test "$kind" = value; and not string match -q -- '*=*' $w
                set skip 1
            end
            continue
        end
        if test $nomore -eq 0
            set -l next (%[1]s_sub "$path" $w)
            if test -n "$next"
                set path $next
                continue
            end
        end
`, p)
	if fallback != "" {
		fmt.Fprintf(&b, "        test -z \"$path\"; and set path %s\n", fq(fallback))
	}
	if len(pts) > 0 {
		fmt.Fprintf(&b, "        if contains -- \"$path\" %s\n            set -g %s_argi $i\n            echo \"$path+\"\n            return\n        end\n", strings.Join(pts, " "), p)
	}
	b.WriteString("    end\n    echo $path\nend\n\n")

	fmt.Fprintf(&b, "function %[1]s_at\n    set -l path (%[1]s_path)\n    contains -- \"$path\" $argv\nend\n\n", p)

	fmt.Fprintf(&b, `function %[1]s_program
    # Complete the routed program's own arguments.
    set -l tokens (commandline -opc)
    %[1]s_path >/dev/null
    set -l cur (commandline -ct)
    set -l rest $tokens[$%[1]s_argi..-1]
    complete --do-complete=(string join -- ' ' (string escape -- $rest) "$cur")
end

`, p)

	b.WriteString("for __c in " + strings.Join(a.Names(), " ") + "\n")
	b.WriteString("    complete -c $__c -f\n")
	root.walk(func(n *node) {
		cond := fmt.Sprintf("-n %s", fq(p+"_at "+fq(n.key())))
		for _, s := range n.subs {
			for i, name := range s.names {
				desc := s.summary
				if i > 0 {
					desc = "alias for " + s.names[0]
				}
				fmt.Fprintf(&b, "    complete -c $__c %s -a %s -d %s\n", cond, fq(name), fq(desc))
			}
		}
		for _, f := range n.flags {
			var parts []string
			for _, s := range f.Short() {
				parts = append(parts, "-s "+s)
			}
			for _, l := range f.Long() {
				parts = append(parts, "-l "+l)
			}
			if f.TakesValue() {
				parts = append(parts, fishAction(f.Complete, p))
			}
			fmt.Fprintf(&b, "    complete -c $__c %s %s -d %s\n", cond, strings.Join(parts, " "), fq(f.Usage))
		}
		switch n.args.Kind {
		case CompleteCommand:
			fmt.Fprintf(&b, "    complete -c $__c %s -a '(__fish_complete_command)'\n", cond)
			fmt.Fprintf(&b, "    complete -c $__c -n %s -a '(%s_program)'\n", fq(p+"_at "+fq(n.key()+"+")), p)
		case CompleteFile:
			fmt.Fprintf(&b, "    complete -c $__c %s -F\n", cond)
		case CompleteDir:
			fmt.Fprintf(&b, "    complete -c $__c %s -a '(__fish_complete_directories)'\n", cond)
		case CompleteChoices:
			fmt.Fprintf(&b, "    complete -c $__c %s -a %s\n", cond, fq(strings.Join(n.args.Words, " ")))
		case CompleteDynamic:
			fmt.Fprintf(&b, "    complete -c $__c %s -a %s\n", cond, fq("("+p+"_dynamic "+n.args.Topic+")"))
		}
	})
	if fallback != "" {
		// Legacy px.sh style: `px curl <TAB>` completes curl's arguments.
		fmt.Fprintf(&b, "    complete -c $__c -n %s -a '(%s_program)'\n", fq(p+"_at "+fq(fallback+"+")), p)
	}
	b.WriteString("end\nset -e __c\n")
	_, err := w.Write(dedupeLines(b.Bytes()))
	return err
}

func fishAction(c Completion, p string) string {
	switch c.Kind {
	case CompleteFile:
		return "-r -F"
	case CompleteDir:
		return "-x -a '(__fish_complete_directories)'"
	case CompleteChoices:
		return "-x -a " + fq(strings.Join(c.Words, " "))
	case CompleteDynamic:
		return "-x -a " + fq("("+p+"_dynamic "+c.Topic+")")
	}
	return "-x"
}

// dedupeLines drops exact repeats of "complete" lines (the fallback rule
// can coincide with the pass-through command's own rule).
func dedupeLines(src []byte) []byte {
	seen := map[string]bool{}
	var out bytes.Buffer
	for _, l := range strings.SplitAfter(string(src), "\n") {
		if strings.HasPrefix(strings.TrimSpace(l), "complete -c") {
			if seen[l] {
				continue
			}
			seen[l] = true
		}
		out.WriteString(l)
	}
	return out.Bytes()
}
