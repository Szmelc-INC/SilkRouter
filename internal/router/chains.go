package router

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/szmelc-inc/silkrouter/internal/proxy"
)

// Methods of proxying a command.
const (
	MethodEnv         = "env"         // proxy variables only (programs that honour them)
	MethodProxychains = "proxychains" // LD_PRELOAD: every TCP connection of the process tree
)

// FindProxychains returns the proxychains binary: bin when set, else
// proxychains4, else proxychains from $PATH.
func FindProxychains(bin string) (string, error) {
	cands := []string{"proxychains4", "proxychains"}
	if bin != "" {
		cands = []string{bin}
	}
	for _, c := range cands {
		if p, err := exec.LookPath(c); err == nil {
			return p, nil
		}
	}
	return "", errors.New("proxychains not found (install proxychains-ng, or set route.proxychains)")
}

// ProxychainsConf renders a proxychains-ng config with p as the only hop.
func ProxychainsConf(p proxy.Proxy) string {
	kind := "http"
	switch p.Scheme {
	case proxy.SOCKS5:
		kind = "socks5"
	case proxy.SOCKS4, proxy.SOCKS4A:
		kind = "socks4"
	}
	hop := fmt.Sprintf("%s %s %d", kind, p.Host, p.Port)
	if p.User != "" {
		hop += " " + p.User + " " + p.Pass
	}
	return strings.Join([]string{
		"# generated by silkrouter; removed when the command exits",
		"strict_chain",
		"quiet_mode",
		"proxy_dns",
		"remote_dns_subnet 224",
		"tcp_read_time_out 15000",
		"tcp_connect_time_out 8000",
		"localnet 127.0.0.0/255.0.0.0",
		"localnet ::1/128",
		"[ProxyList]",
		hop,
		"",
	}, "\n")
}

// ProxychainsWrap returns an Options.Wrap that runs the command under
// proxychains with a temporary config in dir.
func ProxychainsWrap(bin, dir string) func(p proxy.Proxy, args []string) ([]string, func(), error) {
	return func(p proxy.Proxy, args []string) ([]string, func(), error) {
		pc, err := FindProxychains(bin)
		if err != nil {
			return nil, nil, err
		}
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return nil, nil, err
		}
		f, err := os.CreateTemp(dir, "proxychains-*.conf")
		if err != nil {
			return nil, nil, err
		}
		_, werr := f.WriteString(ProxychainsConf(p))
		cerr := f.Close()
		if err := errors.Join(werr, cerr); err != nil {
			os.Remove(f.Name())
			return nil, nil, err
		}
		conf := filepath.Clean(f.Name())
		out := append([]string{pc, "-q", "-f", conf}, args...)
		return out, func() { os.Remove(conf) }, nil
	}
}
